    def _perimeter_cells(self, exclude=None):
        """
        Devuelve todas las celdas del perímetro del grid en (x,y),
        excluyendo las coordenadas en 'exclude'.
        Por petición: excluye (0,0) y (W-1,H-1) => (8,7) en 9x8.
        """
        W = getattr(self, "W", self.grid.width)
        H = getattr(self, "H", self.grid.height)

        # Construye lista del perímetro (sin duplicar esquinas)
        perim = []
        # Fila superior (y=0)
        perim.extend([(x, 0) for x in range(W)])
        # Fila inferior (y=H-1)
        perim.extend([(x, H-1) for x in range(W)])
        # Columna izquierda (x=0), interior (sin esquinas)
        perim.extend([(0, y) for y in range(1, H-1)])
        # Columna derecha (x=W-1), interior (sin esquinas)
        perim.extend([(W-1, y) for y in range(1, H-1)])

        # Excluir duplicados manteniendo orden
        seen = set()
        perim_unique = []
        for p in perim:
            if p not in seen:
                seen.add(p)
                perim_unique.append(p)

        # Exclusiones
        excl = set(exclude or [])
        # Por tu requerimiento explícito:
        excl.add((0, 0))
        excl.add((W-1, H-1))  # (8,7) en 9x8

        # (Opcional) Evita zonas especiales si quedaran al borde
        if hasattr(self, "nursing_pos"):
            excl.add(self.nursing_pos)
        if hasattr(self, "airlock_pos"):
            excl.add(self.airlock_pos)

        # Devuelve perímetro sin excluidos
        return [p for p in perim_unique if p not in excl]

    def _free_perimeter_spawns(self):
        """
        Celdas del perímetro LIBRES para spawnear astronautas.
        Evita posiciones con fuego (y opcionalmente humo, si lo deseas).
        """
        perim = self._perimeter_cells()
        free = []
        for pos in perim:
            # La celda debe estar libre de agentes
            if not self.grid.is_cell_empty(pos):
                continue
            # Evita spawnear sobre fuego
            if pos in self.fire_positions:
                continue
            # (Opcional) Evita spawnear sobre humo
            # if pos in self.smoke_positions:
            #     continue
            free.append(pos)
        return free

    def _place_astronauts_from_entries(self, entry_positions, n, shuffle=True):
        """
        Coloca hasta n astronautas usando primero las entradas del archivo.
        Si faltan, completa con perímetro. Evita apilar cuando es posible.
        """
        rng = getattr(self, "random", None)

        # Preferimos entradas
        candidates = list(entry_positions)
        # Completa con perímetro si faltan lugares
        if len(candidates) < n:
            extras = [p for p in self._free_perimeter_spawns() if p not in candidates]
            if shuffle:
                if rng: rng.shuffle(extras)
                else:   random.shuffle(extras)
            candidates.extend(extras)

        if len(candidates) < n:
            raise RuntimeError(f"No hay suficientes celdas para {n} astronautas.")

        if shuffle:
            if rng: rng.shuffle(candidates)
            else:   random.shuffle(candidates)

        for i in range(n):
            pos = candidates[i]
            if not self.grid.is_cell_empty(pos):
                # busca vecino libre inmediato
                for nb in self.neighbors4(pos):
                    if self.grid.is_cell_empty(nb):
                        pos = nb; break

            strat = (self.agent_strategies[i] if isinstance(self.agent_strategies, (list, tuple))
                    and i < len(self.agent_strategies) else self.default_strategy)

            a = Astronaut(i, self, strategy=strat)
            # a.max_ap = self.max_ap  # innecesario: el Astronaut ya lee model.max_ap
            self.grid.place_agent(a, pos)
            self.schedule.add(a)

