    def _is_buildable_floor(self, pos):
        """Se puede colocar fuego/humo/POI aquí (no exterior, no zonas especiales)."""
        x, y = pos
        # Usa self.W/self.H (o self.grid.width/height, ambos sirven si están sincronizados)
        W, H = self.W, self.H

        # Evitar perímetro/exterior
        if x in (0, W-1) or y in (0, H-1):
            return False

        # Evitar Nursing/Airlock
        if pos in (self.nursing_pos, self.airlock_pos):
            return False

        return True


    def _place_fire(self, n):
        rng = getattr(self, "random", None)
        attempts = 0
        while n > 0 and attempts < 10000:
            x = (rng.randint(1, self.W - 2) if rng else random.randint(1, self.W - 2))
            y = (rng.randint(1, self.H - 2) if rng else random.randint(1, self.H - 2))
            pos = (x, y)
            if self._is_buildable_floor(pos) and pos not in self.fire_positions:
                self.fire_positions.add(pos)   # <-- add, no append
                n -= 1
            attempts += 1

    def _place_initial_smoke(self, n):
        rng = getattr(self, "random", None)
        attempts = 0
        while n > 0 and attempts < 10000:
            x = (rng.randint(1, self.W - 2) if rng else random.randint(1, self.W - 2))
            y = (rng.randint(1, self.H - 2) if rng else random.randint(1, self.H - 2))
            pos = (x, y)
            if (self._is_buildable_floor(pos)
                and pos not in self.fire_positions
                and pos not in self.smoke_positions):
                self.smoke_positions.add(pos)  # <-- add
                n -= 1
            attempts += 1

    def _place_pois(self, n):
        rng = getattr(self, "random", None)
        attempts = 0
        while n > 0 and attempts < 10000:
            x = (rng.randint(1, self.W - 2) if rng else random.randint(1, self.W - 2))
            y = (rng.randint(1, self.H - 2) if rng else random.randint(1, self.H - 2))
            pos = (x, y)
            if self._is_buildable_floor(pos) and pos not in self.poi_positions:
                self.poi_positions.add(pos)  # <-- add
                # Tipos: 'alive', 'dead', 'none'
                choice = (rng.choice(["alive", "dead", "none"]) if rng else random.choice(["alive", "dead", "none"]))
                self.victim_status[pos] = choice
                n -= 1
            attempts += 1


    def count_lost(self):
        """Cuenta víctimas 'dead' (no cuenta falsas alarmas)."""
        return sum(1 for s in self.victim_status.values() if s == "dead")

    def _place_pois_pool(self, num_alive, num_false, num_dead=0):
        pool = (["alive"] * max(0, num_alive)
                + ["none"] * max(0, num_false)
                + ["dead"] * max(0, num_dead))
        rng = getattr(self, "random", None)
        if rng: rng.shuffle(pool)
        else: random.shuffle(pool)

        attempts = 0
        for status in pool:
            placed = False
            while not placed and attempts < 20000:
                x = (rng.randint(1, self.W - 2) if rng else random.randint(1, self.W - 2))
                y = (rng.randint(1, self.H - 2) if rng else random.randint(1, self.H - 2))
                pos = (x, y)
                attempts += 1
                if not self._is_buildable_floor(pos):
                    continue
                if pos in self.poi_positions or pos in self.fire_positions or pos in self.smoke_positions:
                    continue
                self.poi_positions.add(pos)     # <-- add
                self.victim_status[pos] = status
                placed = True

    # ---------- DINÁMICA DEL ENTORNO ----------
    def _explode(self, pos):
        """
        Explosión desde 'pos':
          - Paredes: suben daño; al cruzar a 2 (+1 marcador) quedan transitables.
          - Puertas: se abren, pero **NO** suman daño.
          - Si la arista ya es transitable, afecta al otro lado (knockdown/POI muere).
        """
        for nb in self.neighbors4(pos):
            e = self._edge(pos, nb)

            # Daño a pared (solo cuenta al cruzar de <2 a 2)
            if e in self.wall_damage_edge:
                prev = self.wall_damage_edge.get(e, 0)
                new = min(prev + 1, 2)
                self.wall_damage_edge[e] = new
                if prev < 2 and new == 2:
                    self.damage_markers += 1  # colapso de pared
            # Puerta: abrir sin dañar
            elif e in self.door_state_edge:
                if self.door_state_edge[e] != "open":
                    self.door_state_edge[e] = "open"  # <-- sin incrementar damage_markers

            # Efectos al otro lado si ya es transitable
            if self.can_traverse(pos, nb):
                for a in self.grid.get_cell_list_contents([nb]):
                    if isinstance(a, Astronaut):
                        a.knockdown()
                if nb in self.poi_positions:
                    self.victim_status[nb] = "dead"

    def _spread_fire(self):
        rng = getattr(self, "random", None)
        x = (rng.randint(1, self.W - 2) if rng else random.randint(1, self.W - 2))
        y = (rng.randint(1, self.H - 2) if rng else random.randint(1, self.H - 2))
        pos = (x, y)

        if pos in self.fire_positions:
            self._explode(pos)

        elif pos in self.smoke_positions:
            self.smoke_positions.discard(pos)  # <-- discard
            self.fire_positions.add(pos)       # <-- add

        else:
            if pos not in self.fire_positions:
                self.smoke_positions.add(pos)  # <-- add

    # ---------- CICLO ----------
    def step(self):
        if self.game_over:
            return

        # Agentes
        self.schedule.step()

        # (Opcional) ya NO reponemos POIs, salvo que explícitamente quieras:
        if self.replenish_pois and len(self.poi_positions) < 3:
            self._place_pois(3 - len(self.poi_positions))

        # Entorno
        self._spread_fire()

        # Avance y registro
        self.turn += 1
        self.current_step = self.turn
        self.datacollector.collect(self)

        # Condiciones de término
        rescued_total = sum(getattr(a, "victims_saved", 0) for a in self.schedule.agents)
        lost_total    = self.count_lost()

        if rescued_total >= self.rescued_target:
            self.game_over = True
            self.status = "Misión exitosa"
            self.finished_at = self.turn
            return

        if lost_total >= self.lost_threshold:
            self.game_over = True
            self.status = "Demasiadas víctimas perdidas"
            self.finished_at = self.turn
            return

        if self.damage_markers >= self.damage_threshold:
            self.game_over = True
            self.status = "Base colapsada"
            self.finished_at = self.turn
            return

