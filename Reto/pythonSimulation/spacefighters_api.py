def get_grid_for_animation(model):
    g = np.zeros((model.grid.height, model.grid.width), dtype=int)

    # 1) Lugares especiales primero (para no tapar astronautas después)
    nx, ny = model.nursing_pos; g[ny, nx] = NURSING_CODE
    axx, ayy = model.airlock_pos; g[ayy, axx] = AIRLOCK_CODE

    # 2) Estados de celda
    for (x, y) in model.smoke_positions: g[y, x] = SMOKE
    for (x, y) in model.fire_positions:  g[y, x] = FIRE

    # 3) POIs diferenciados por estado
    #    - 'alive' -> morado (POI_VICTIM)
    #    - 'dead'  -> naranja (POI_DEAD)
    #    - 'none'  -> lila   (POI_FALSE)
    for (x, y) in model.poi_positions:
        status = model.victim_status.get((x, y), 'none')
        if status == 'alive':
            g[y, x] = POI_VICTIM
        elif status == 'dead':
            g[y, x] = POI_DEAD
        else:
            g[y, x] = POI_FALSE

    # 4) Astronautas encima (para que se vean siempre)
    for a in model.schedule.agents:
        if getattr(a, "pos", None) is not None:
            x, y = a.pos
            g[y, x] = ASTRONAUT

    return g

def _edge_to_segment(a, b):
    (x1, y1), (x2, y2) = a, b
    if x1 != x2:  # segmento vertical
        x = min(x1, x2) + 0.5
        y0 = min(y1, y2) - 0.5
        y1_ = max(y1, y2) + 0.5
        return [(x, y0), (x, y1_)]
    else:         # segmento horizontal
        y = min(y1, y2) + 0.5
        x0 = min(x1, x2) - 0.5
        x1_ = max(x1, x2) + 0.5
        return [(x0, y), (x1_, y)]

def _compute_barrier_segments(model):
    walls_intact, walls_damaged, doors_closed, doors_open = [], [], [], []
    for e, dmg in model.wall_damage_edge.items():
        if dmg < 2:
            a, b = tuple(e)
            seg = _edge_to_segment(a, b)
            if dmg == 0:
                walls_intact.append(seg)
            else:
                walls_damaged.append(seg)
    for e, st in model.door_state_edge.items():
        a, b = tuple(e)
        seg = _edge_to_segment(a, b)
        if st == "closed":
            doors_closed.append(seg)
        else:
            doors_open.append(seg)
    return walls_intact, walls_damaged, doors_closed, doors_open

def animate_model(model, max_steps=200, interval=200, title_prefix=""):
    fig, ax = plt.subplots(figsize=(6,6))
    ax.set_xticks([]); ax.set_yticks([])

    # Rejilla
    ax.set_xticks(np.arange(-0.5, model.grid.width, 1), minor=True)
    ax.set_yticks(np.arange(-0.5, model.grid.height, 1), minor=True)
    ax.grid(which='minor', color='lightgray', linestyle='-', linewidth=0.5, alpha=0.4)

    im = ax.imshow(get_grid_for_animation(model), cmap=cmap, norm=norm, interpolation="nearest")
    title_text = ax.set_title(
        f"{title_prefix} | Turno {model.turn} | "
        f"Daño: {model.damage_markers}/{model.damage_threshold} "
        f"(restan {max(0, model.damage_threshold - model.damage_markers)}) | {model.status}"
    )

    wall0_lines = LineCollection([], colors='#8B5A2B', linewidths=2)
    wall1_lines = LineCollection([], colors='#EF6C00', linewidths=2)
    doorC_lines = LineCollection([], colors='#1B5E20', linewidths=2)
    doorO_lines = LineCollection([], colors='#66BB6A', linewidths=2, linestyles='dashed')
    ax.add_collection(wall0_lines)
    ax.add_collection(wall1_lines)
    ax.add_collection(doorC_lines)
    ax.add_collection(doorO_lines)

    def _upd(_i):
        if _i > 0 and not model.game_over:
            model.step()
        im.set_data(get_grid_for_animation(model))
        w0, w1, dc, do = _compute_barrier_segments(model)
        wall0_lines.set_segments(w0)
        wall1_lines.set_segments(w1)
        doorC_lines.set_segments(dc)
        doorO_lines.set_segments(do)
        title_text.set_text(
            f"{title_prefix} | Turno {model.turn} | "
            f"Daño: {model.damage_markers}/{model.damage_threshold} "
            f"(restan {max(0, model.damage_threshold - model.damage_markers)}) | {model.status}"
        )
        return (im, wall0_lines, wall1_lines, doorC_lines, doorO_lines, title_text)

    ani = animation.FuncAnimation(fig, _upd, frames=max_steps, interval=interval, blit=False)
    plt.tight_layout()
    return ani

