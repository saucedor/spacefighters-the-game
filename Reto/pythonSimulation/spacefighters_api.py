class Astronaut(Agent):
    """
    IA mejorada con aristas (paredes/puertas entre celdas):
      - BFS para acercarse a objetivo (permite puertas cerradas en planificación).
      - Abre puertas cerradas (1 AP) antes de entrar; con 1 AP puede abrir y esperar.
      - Prioriza: POI vivo -> POI muerto -> POI none -> fuego -> humo (selección de objetivo en parte 2).
      - Seguridad adyacente (apagar/limpiar) antes de avanzar (en parte 2).
      - Evita colisiones (no entra a celdas ocupadas).
      - Métricas para DataCollector (contadores en parte 2).

    Requiere en el modelo:
      - grid (SingleGrid recomendado) / is_cell_empty disponible
      - neighbors4(pos)
      - edge_is_wall_solid(a,b), edge_is_door_closed(a,b), _edge(a,b)
      - nursing_pos, airlock_pos
      - fire_positions, smoke_positions, poi_positions, victim_status
      - (opcional) model.random para reproducibilidad
    """
    VALID_STRATEGIES = {"reasoned", "random"}

    def __init__(self, unique_id, model, strategy=None):
        super().__init__(model)
        # AP y estado
        self.max_ap = getattr(model, "max_ap", 4)
        self.ap = self.max_ap
        self.carrying = False
        self.carrying_status = None  # 'alive' | 'dead'
        # Métricas (se usan en DataCollector)
        self.victims_saved = 0
        self.fires_extinguished = 0
        self.smoke_cleared = 0
        self.pois_found = 0
        # Log
        self.log = []  # Para registrar acciones por turno
        # Objetivo “pegajoso” (se usa en parte 2 del step)
        self.current_target = None


        # === Estrategia ===
        self.strategy = strategy or getattr(model, "default_strategy", "reasoned")
        if self.strategy not in self.VALID_STRATEGIES:
            self.strategy = "reasoned"

    def set_strategy(self, strategy: str):
        """Cambia la estrategia del agente en tiempo de ejecución."""
        if strategy not in self.VALID_STRATEGIES:
            raise ValueError(f"Estrategia inválida: {strategy}. Usa {self.VALID_STRATEGIES}.")
        self.strategy = strategy



    # ----------------- Helpers de vecindad y aristas -----------------
    def _adjacent4(self, pos):
        # Lo mantenemos por compatibilidad, aunque preferimos model.neighbors4
        x, y = pos
        return [(x+1,y), (x-1,y), (x,y+1), (x,y-1)]

    def _edge_is_wall(self, a, b):
        return self.model.edge_is_wall_solid(a, b)

    def _edge_is_door_closed(self, a, b):
        return self.model.edge_is_door_closed(a, b)

    def _cell_free(self, pos):
        """True si la celda está libre (evita colisiones)."""
        try:
            return self.model.grid.is_cell_empty(pos)
        except AttributeError:
            # Si fuera MultiGrid, evitamos entrar si hay otro Astronaut
            occupants = self.model.grid.get_cell_list_contents([pos])
            return all((o is self) or (not isinstance(o, Astronaut)) for o in occupants)

    # ----------------- Acciones sobre puertas -----------------
    def open_door_between(self, a, b):
        """Abre la puerta en la arista a<->b (si está cerrada) gastando 1 AP."""
        if self.ap >= 1 and self._edge_is_door_closed(a, b):
            e = self.model._edge(a, b)
            self.model.door_state_edge[e] = "open"
            self.ap -= 1
            self.log.append(f"Abre puerta entre {a} y {b}. AP={self.ap}")
            return True
        return False

    # ----------------- Movimiento -----------------
    def _try_move(self, new_pos):
        """
        Intenta mover al agente a new_pos:
          - No entra a fuego.
          - No atraviesa pared sólida.
          - Si hay puerta cerrada en la arista, puede: abrir+entrar (AP >= 1 + move_cost)
            o abrir solo si tiene 1 AP (prepara el siguiente turno).
          - Evita colisiones: no entra a celdas ocupadas.
        """
        if self.ap <= 0 or new_pos == self.pos:
            return False

        cur = self.pos

        # No pisar fuego
        if new_pos in self.model.fire_positions:
            return False

        # Pared sólida en la arista
        if self._edge_is_wall(cur, new_pos):
            return False

        move_cost = 1 + (1 if self.carrying else 0)
        rng = getattr(self.model, "random", None)

        # Puerta cerrada en la arista
        if self._edge_is_door_closed(cur, new_pos):
            total = 1 + move_cost  # abrir (1) + mover (move_cost)

            if self.ap >= total:
                # Solo abrimos si podemos entrar y la celda está libre (evita gastar AP inútil)
                if not self._cell_free(new_pos):
                    return False
                self.open_door_between(cur, new_pos)   # -1 AP
                # Re-check por seguridad (no debería cambiar entre líneas, pero es barato)
                if not self._cell_free(new_pos):
                    return False
                self.ap -= move_cost
                self.model.grid.move_agent(self, new_pos)
                return True

            elif self.ap == 1:
                # Abrir y preparar avance para el siguiente turno (aunque la celda esté ocupada)
                return self.open_door_between(cur, new_pos)

            return False

        if not self._cell_free(new_pos):
            return False

        # Movimiento normal (sin puerta)
        if self.ap >= move_cost and self._cell_free(new_pos):
            self.ap -= move_cost
            self.model.grid.move_agent(self, new_pos)
            return True

        return False

    # ----------------- Planificación -----------------
    def _astar_next_step(self, start, goal):
        """A* sobre celdas con aristas: pared sólida bloquea; puerta cerrada se permite (se abrirá al entrar)."""
        if start == goal:
            return None
        W, H = self.model.grid.width, self.model.grid.height

        def h(p):  # heurística Manhattan
            return abs(p[0]-goal[0]) + abs(p[1]-goal[1])

        open_set = {start}
        came_from = {}
        g = {start: 0}
        f = {start: h(start)}

        import heapq
        heap = [(f[start], start)]

        while heap:
            _, current = heapq.heappop(heap)
            if current == goal:
                # reconstruir el primer paso
                step = current
                while came_from.get(step, start) != start:
                    step = came_from[step]
                return step

            open_set.discard(current)

            for nb in self.model.neighbors4(current):
                # pared sólida NO se puede planear
                if not self.model.planning_passable(current, nb):
                    continue

                tentative_g = g[current] + 1  # costo uniforme
                if tentative_g < g.get(nb, 1e9):
                    came_from[nb] = current
                    g[nb] = tentative_g
                    fnb = tentative_g + h(nb)
                    f[nb] = fnb
                    if nb not in open_set:
                        open_set.add(nb)
                        heapq.heappush(heap, (fnb, nb))
        return None


    def _bfs_next_step(self, start, goal):
        """
        BFS sobre celdas, considerando aristas:
          - Pared sólida bloquea planificación.
          - Puerta cerrada se permite (se abrirá al intentar entrar).
        Devuelve el PRIMER paso desde 'start' hacia 'goal', o None si no hay ruta.
        """
        if start == goal:
            return None

        W, H = self.model.grid.width, self.model.grid.height
        q = deque([start])
        visited = {start}
        parent = {start: None}

        while q:
            cur = q.popleft()
            for nb in self.model.neighbors4(cur):
                if nb in visited:
                    continue
                # En planificación: pared sólida bloquea; puerta cerrada se permite
                if not self.model.planning_passable(cur, nb):
                    continue
                visited.add(nb)
                parent[nb] = cur
                if nb == goal:
                    # reconstruir primer paso
                    step = nb
                    while parent[step] != start:
                        step = parent[step]
                    return step
                q.append(nb)
        return None


    # ----------------- Movimiento aleatorio dirigido (opcional) -----------------
    def _random_move(self, prefer_towards=None):
        """
        Intenta moverse a un vecino válido:
          - Solo a vecinos atravesables (sin pared ni puerta cerrada), sin fuego y libres.
          - Si 'prefer_towards' se da, prefiere el vecino que reduce la distancia Manhattan al objetivo.
        """
        rng = getattr(self.model, "random", None)
        neighbors = list(self.model.neighbors4(self.pos))

        # Filtra solo vecinos válidos
        valid = []
        for nb in neighbors:
            if nb in self.model.fire_positions:
                continue
            if self._edge_is_wall(self.pos, nb):
                continue
            if self._edge_is_door_closed(self.pos, nb):
                # _random_move no abre puertas; solo camina si ya está libre
                continue
            if not self._cell_free(nb):
                continue
            valid.append(nb)

        if not valid:
            return False

        # Ordena por distancia al objetivo si se proporciona
        if prefer_towards is not None:
            valid.sort(key=lambda p: abs(p[0]-prefer_towards[0]) + abs(p[1]-prefer_towards[1]))

        # Intenta en ese orden (determinista si usas self.model.random y no re-ordenas)
        for nb in valid:
            if self._try_move(nb):
                return True

        # Si no hay vecinos válidos, intenta limpiar o apagar en su celda
        if self.pos in self.model.smoke_positions and self.ap >= 1:
            self.clear_smoke(self.pos)
            self.log.append(f"Limpia humo en su celda {self.pos}. AP={self.ap}")
            return True
        if self.pos in self.model.fire_positions and self.ap >= 2:
            self.extinguish_fire(self.pos)
            self.log.append(f"Apaga fuego en su celda {self.pos}. AP={self.ap}")
            return True

        return False

    def _do_safety_adjacent(self):
        """Acciones solo si la arista hacia el vecino es transitable: fuego > humo."""
        for nb in self.model.neighbors4(self.pos):
            if self.model.can_traverse(self.pos, nb) and nb in self.model.fire_positions and self.ap >= 2:
                self.extinguish_fire(nb)
                self.log.append(f"Apaga fuego adyacente en {nb}. AP={self.ap}")
                return True
        for nb in self.model.neighbors4(self.pos):
            if self.model.can_traverse(self.pos, nb) and nb in self.model.smoke_positions and self.ap >= 1:
                self.clear_smoke(nb)
                self.log.append(f"Limpia humo adyacente en {nb}. AP={self.ap}")
                return True
        return False

    def _neighbors_von_neumann(self, pos):
        # (No usada; preferimos model.neighbors4, se deja por compatibilidad)
        x, y = pos
        candidates = [(x+1,y), (x-1,y), (x,y+1), (x,y-1)]
        valid = []
        for nx, ny in candidates:
            if 0 <= nx < self.model.grid.width and 0 <= ny < self.model.grid.height:
                valid.append((nx, ny))
        return valid

    def _nearest(self, positions):
        if not positions:
            return None
        x0, y0 = self.pos
        return min(positions, key=lambda p: abs(p[0]-x0)+abs(p[1]-y0))

    def _select_target(self):
        """Prioridad: POI vivo -> POI muerto -> POI none -> fuego -> humo."""
        alive_pois = [p for p in self.model.poi_positions if self.model.victim_status.get(p) == 'alive']
        dead_pois  = [p for p in self.model.poi_positions if self.model.victim_status.get(p) == 'dead']
        any_pois   = [p for p in self.model.poi_positions if self.model.victim_status.get(p) == 'none']
        for bucket in (alive_pois, dead_pois, any_pois, self.model.fire_positions, self.model.smoke_positions):
            if bucket:
                return self._nearest(bucket)
        return None

    def _target_still_valid(self, t):
        """Verifica si el objetivo sigue existiendo en el mundo."""
        if t is None:
            return False
        # Si lleva víctima, el objetivo es fijo y lo maneja _choose_or_keep_target
        # Para el resto: sigue válido si está en alguna de estas colecciones actuales
        if t in self.model.poi_positions:
            return True
        if t in self.model.fire_positions:
            return True
        if t in self.model.smoke_positions:
            return True
        return False

    def _choose_or_keep_target(self):
        """Objetivo 'pegajoso': conserva el target si sigue válido; si no, selecciona uno nuevo."""
        if self.carrying:
            return self.model.nursing_pos if self.carrying_status == 'alive' else self.model.airlock_pos
        if self._target_still_valid(self.current_target):
            return self.current_target
        # Elegir uno nuevo
        self.current_target = self._select_target()
        return self.current_target

    def extinguish_fire(self, pos):
        if self.ap >= 2 and pos in self.model.fire_positions:
            try:
                self.model.fire_positions.remove(pos)
            except ValueError:
                # Ya fue removido por otro efecto concurrente
                return False
            self.fires_extinguished += 1
            self.ap -= 2
            return True
        return False

    def clear_smoke(self, pos):
        if self.ap >= 1 and pos in self.model.smoke_positions:
            try:
                self.model.smoke_positions.remove(pos)
            except ValueError:
                return False
            self.smoke_cleared += 1
            self.ap -= 1
            return True
        return False

    def _interact_here(self):
        """Levanta POI si está en la celda. Las falsas alarmas ('none') se descartan."""
        if self.pos in self.model.poi_positions:
            status = self.model.victim_status.get(self.pos, 'none')
            self.pois_found += 1
            # Remueve el POI del tablero
            try:
                self.model.poi_positions.remove(self.pos)
            except ValueError:
                pass
            self.model.victim_status.pop(self.pos, None)
            # Si es víctima (viva o muerta) y no trae carga, cargarla
            if status in ('alive', 'dead') and not self.carrying:
                self.carrying = True
                self.carrying_status = status
                self.log.append(f"Recoge víctima {status} en {self.pos}.")

    def _advance_towards(self, target_pos):
        """Da un paso (A* con fallback a BFS) hacia target_pos; con fallbacks de puerta/side-step."""
        if self.ap <= 0:
            return False

        # A* primero
        step = self._astar_next_step(self.pos, target_pos)
        if step is None:
            step = self._bfs_next_step(self.pos, target_pos)

        if step is None:
            return False

        # Intentar mover al 'step'
        old = self.pos
        # Si hay puerta cerrada justo hacia ese paso, intenta abrir+entrar si alcanza AP; si no, abre solo
        if self._edge_is_door_closed(self.pos, step):
            # _try_move intentará abrir+entrar si hay AP suficiente; si no, con AP==1 abrirá y regresará True
            moved = self._try_move(step)
            if moved:
                self.log.append(f"Avanza hacia {target_pos}: {old} -> {self.pos}. AP={self.ap}")
                return True
            # Si no pudo, al menos intenta abrir solo (si no se abrió ya)
            if self._open_adjacent_door_towards(target_pos):
                return True
            # Si tampoco, intenta side-step
            return self._sidestep_towards(target_pos)

        # Sin puerta de por medio: movimiento normal
        moved = self._try_move(step)
        if moved:
            self.log.append(f"Avanza hacia {target_pos}: {old} -> {self.pos}. AP={self.ap}")
            return True

        # Si no entró (ocupado o sin AP), prueba side-step
        if self._sidestep_towards(target_pos):
            return True

        # Nada
        return False

    # ----------------- Lógica por turno -----------------
    def step_reasoned(self):
        # Inicio de turno
        self.ap = self.max_ap
        self.log = [f"Astronauta {self.unique_id} inicia turno en {self.pos} con {self.ap} AP."]
        self._interact_here()

        guard = 50  # Evita loops raros en un mismo turno
        while self.ap > 0 and guard > 0:
            guard -= 1

            # Si trae víctima: prioridad absoluta = entregar
            if self.carrying:
                target = self.model.nursing_pos if self.carrying_status == 'alive' else self.model.airlock_pos

                # Seguridad adyacente primero
                if self._do_safety_adjacent():
                    continue

                # ¿Ya está en el punto de entrega?
                if self.pos == target:
                    if self.carrying_status == 'alive':
                        self.victims_saved += 1
                        self.log.append(f"Entrega víctima viva en {target}.")
                    else:
                        self.log.append(f"Entrega víctima muerta en {target}.")
                    self.carrying = False
                    self.carrying_status = None
                    self.current_target = None  # Reinicia objetivo
                    continue

                # Avanzar hacia el punto de entrega
                if self._advance_towards(target):
                    self._interact_here()  # Por si pisa un POI
                    continue

                # Sin ruta: intenta moverse acercándose o termina turno
                if self._random_move(prefer_towards=target):
                    self._interact_here()
                    continue

                # Nada que hacer: termina turno
                self.log.append("Atorado cargando: sin movimientos posibles. Termina turno.")
                self.ap = 0
                break
            # --- Si NO trae víctima ---
            # Seguridad adyacente primero
            if self._do_safety_adjacent():
                continue

            # ¿Hay algo aquí para interactuar? (p. ej., recoger POI)
            prev_carry = self.carrying
            self._interact_here()
            if self.carrying and not prev_carry:
                # Tras recoger, ahora su objetivo es punto de entrega
                continue

            # Elegir o mantener objetivo
            target = self._choose_or_keep_target()

            if target is None:
                # Nada que perseguir: moverse un paso válido (dirigido si hay rastro de target previo)
                if self._random_move():
                    self._interact_here()
                    continue
                else:
                    self.log.append("Sin objetivo y sin movimientos posibles. Termina turno.")
                    self.ap = 0
                    break

            # Avanzar hacia el objetivo elegido
            if self._advance_towards(target):
                self._interact_here()
                continue

            # Si no pudo avanzar (p. ej., puerta cerrada que abrió pero no alcanza a entrar, o bloqueo):
            # -> intenta moverse acercándose (sin abrir puertas aquí)
            if self._random_move(prefer_towards=target):
                self._interact_here()
                continue

            # (Opcional) Intentar brecha de pared si el modelo la soporta
            if hasattr(self.model, "damage_wall_edge"):
                # Heurística simple: intenta brechar hacia el vecino que acerque al objetivo (cuesta 2 AP)
                if self.ap >= 2:
                    best = None
                    best_score = 10**9
                    for nb in self.model.neighbors4(self.pos):
                        e = self.model._edge(self.pos, nb)
                        if e in self.model.wall_damage_edge and self.model.wall_damage_edge[e] < 2:
                            score = abs(nb[0]-target[0]) + abs(nb[1]-target[1])
                            if score < best_score:
                                best = nb; best_score = score
                    if best is not None:
                        prev = self.model.wall_damage_edge[self.model._edge(self.pos, best)]
                        if self.model.damage_wall_edge(self.pos, best, inc=1):
                            self.ap -= 2
                            self.log.append(f"Brecha pared hacia {best} (daño {prev}-> {self.model.wall_damage_edge[self.model._edge(self.pos, best)]}). AP={self.ap}")
                            continue

            # Nada funcionó: termina turno
            self.log.append("No pudo avanzar y no hay movimientos posibles. Termina turno.")
            self.ap = 0
            break

        if guard == 0:
            self.log.append("Guard de seguridad agotado. Termina turno por prevención.")
            self.ap = 0

        # Si no pudo moverse ni interactuar, intenta limpiar humo o apagar fuego en su celda
        if self.pos in self.model.smoke_positions and self.ap >= 1:
            self.clear_smoke(self.pos)
            self.log.append(f"Limpia humo en su celda {self.pos}. AP={self.ap}")
            return
        if self.pos in self.model.fire_positions and self.ap >= 2:
            self.extinguish_fire(self.pos)
            self.log.append(f"Apaga fuego en su celda {self.pos}. AP={self.ap}")
            return

    def _step_random(self):
        self.ap = self.max_ap
        self.log = [f"Astronauta {self.unique_id} (random) inicia turno en {self.pos} con {self.ap} AP."]
        self._interact_here()

        rng = getattr(self.model, "random", None)
        rand = (rng.random if rng else random.random)

        guard = 50
        while self.ap > 0 and guard > 0:
            guard -= 1

            # 30%: acción de seguridad adyacente (apagar/limpiar)
            if rand() < 0.30 and self._do_safety_adjacent():
                self.log.append("Random: acción de seguridad adyacente.")
                continue

            # Si carga: 60% de moverse 'dirigido' hacia el punto de entrega
            prefer = None
            if self.carrying:
                tgt = self.model.nursing_pos if self.carrying_status == 'alive' else self.model.airlock_pos
                if rand() < 0.60:
                    prefer = tgt

            old = self.pos
            if self._random_move(prefer_towards=prefer):
                if self.pos != old:
                    self.log.append(f"Random: se mueve {old} -> {self.pos}. AP={self.ap}")
                self._interact_here()
                continue

            # Si no pudo moverse, limpiar/apagar en su celda
            acted = False
            if self.pos in self.model.smoke_positions and self.ap >= 1:
                self.clear_smoke(self.pos)
                self.log.append(f"Random: limpia humo en {self.pos}. AP={self.ap}")
                acted = True
            elif self.pos in self.model.fire_positions and self.ap >= 2:
                self.extinguish_fire(self.pos)
                self.log.append(f"Random: apaga fuego en {self.pos}. AP={self.ap}")
                acted = True
            if acted:
                continue
            # 20%: intentar brecha aleatoria (si hay pared y alcanza AP)
            if rand() < 0.20 and hasattr(self.model, "damage_wall_edge") and self.ap >= 2:
                neigh = list(self.model.neighbors4(self.pos))
                if rng: rng.shuffle(neigh)
                else: random.shuffle(neigh)
                for nb in neigh:
                    e = self.model._edge(self.pos, nb)
                    if e in self.model.wall_damage_edge and self.model.wall_damage_edge[e] < 2:
                        prev = self.model.wall_damage_edge.get(e, 0)
                        if self.model.damage_wall_edge(self.pos, nb, inc=1):
                            self.ap -= 2
                            newd = self.model.wall_damage_edge.get(e, 0)
                            self.log.append(f"Random: brecha pared hacia {nb} (daño {prev}->{newd}). AP={self.ap}")
                            break
                else:
                    # No rompió nada
                    pass
                continue

            # Nada útil
            self.log.append("Random: sin acciones útiles. Termina turno.")
            self.ap = 0
            break

        if guard == 0:
            self.log.append("Random: guard agotado. Termina turno por prevención.")
            self.ap = 0


    def step(self):
        """Ejecuta la estrategia seleccionada: 'reasoned' o 'random'."""
        if self.strategy == "random":
            return self._step_random()
        # Default
        return self.step_reasoned()


    def knockdown(self):
        """
        Derribo por explosión:
        - Si estaba cargando, suelta y la víctima muere en su celda.
        - Reubica al astronauta en una celda LIBRE del perímetro (o la primera libre que encuentre).
        - Termina su turno.
        """
        # Si cargaba, suelta y muere
        if self.carrying and self.carrying_status in ("alive", "dead"):
            # Añade/actualiza POI muerto en la celda actual
            if isinstance(self.model.poi_positions, list):
                if self.pos not in self.model.poi_positions:
                    self.model.poi_positions.append(self.pos)
            else:
                self.model.poi_positions.add(self.pos)
            self.model.victim_status[self.pos] = "dead"
            self.carrying = False
            self.carrying_status = None
            self.log.append(f"Derribado: suelta víctima que muere en {self.pos}.")

        # Buscar perímetro libre
        perimeter = self.model._free_perimeter_spawns()
        empty_perimeter = [p for p in perimeter if self.model.grid.is_cell_empty(p)]

        new_pos = None
        if empty_perimeter:
            # Usa self.model.random si la tienes configurada; si no, random global
            rng = getattr(self.model, "random", None)
            new_pos = (rng.choice(empty_perimeter) if rng else random.choice(empty_perimeter))
        else:
            # Fallback: primera celda libre que encontremos (interior o borde)
            for y in range(self.model.H):
                for x in range(self.model.W):
                    pos = (x, y)
                    if self.model.grid.is_cell_empty(pos):
                        new_pos = pos
                        break
                if new_pos is not None:
                    break

        if new_pos is not None:
            old_pos = self.pos
            self.model.grid.move_agent(self, new_pos)
            self.log.append(f"Derribado: movido de {old_pos} a perímetro/seguro {new_pos}.")
        else:
            self.log.append("Derribado: sin celda libre para reubicar (permanece en su lugar).")

        # Termina su turno
        self.ap = 0


    def step(self):
        self.log = [f"Astronauta {self.unique_id} inicia turno en {self.pos} con {self.max_ap} AP."]
        self.ap = self.max_ap
        self._interact_here()

        while self.ap > 0:
            if self.carrying:
                target = self.model.nursing_pos if self.carrying_status == 'alive' else self.model.airlock_pos

                if self._do_safety_adjacent():
                    self.log.append(f"Realiza acción de seguridad adyacente en {self.pos}.")
                    continue

                if self.pos == target:
                    if self.carrying_status == 'alive':
                        self.victims_saved += 1
                        self.log.append(f"Entrega víctima viva en {target}.")
                    else:
                        self.log.append(f"Entrega víctima muerta en {target}.")
                    self.carrying = False
                    self.carrying_status = None
                    continue

                if self._advance_towards(target):
                    self.log.append(f"Se mueve hacia {target}.")
                    self._interact_here()
                    continue

                old = self.pos
                if self._random_move():
                    self.log.append(f"Se mueve aleatoriamente: {old} -> {self.pos}.")
                    continue
                else:
                    self.log.append("Atorado: sin movimientos posibles. Termina su turno.")
                    self.ap = 0
                    break

                self.log.append(f"Se mueve aleatoriamente desde {self.pos}.")
                continue

            if self._do_safety_adjacent():
                self.log.append(f"Realiza acción de seguridad adyacente en {self.pos}.")
                continue

            prev_carry = self.carrying
            self._interact_here()
            if self.carrying and not prev_carry:
                self.log.append(f"Recoge víctima {self.carrying_status} en {self.pos}.")
                continue

            target = self._select_target()
            if target is None:
                old = self.pos
                if self._random_move():
                    self.log.append(f"Se mueve aleatoriamente: {old} -> {self.pos}.")
                    continue
                else:
                    self.log.append("Atorado: sin movimientos posibles. Termina su turno.")
                    self.ap = 0
                    break
                self.log.append(f"No hay objetivo. Se mueve aleatoriamente desde {self.pos}.")
                continue

            if self._advance_towards(target):
                self.log.append(f"Se mueve hacia objetivo en {target}.")
                self._interact_here()
                continue

            old = self.pos
            if self._random_move():
                    self.log.append(f"Se mueve aleatoriamente: {old} -> {self.pos}.")
                    continue
            else:
                    self.log.append("Atorado: sin movimientos posibles. Termina su turno.")
                    self.ap = 0
                    break
            self.log.append(f"No pudo avanzar. Se mueve aleatoriamente desde {self.pos}.")

    def _dist(self, a, b):
        return abs(a[0]-b[0]) + abs(a[1]-b[1])

    def _open_adjacent_door_towards(self, target):
        """
        Abre (1 AP) la PUERTA CERRADA en la dirección que más acerque al target.
        Útil cuando no pudimos movernos pero queremos preparar el avance del próximo paso.
        """
        if self.ap <= 0 or target is None:
            return False
        best = None
        best_d = 10**9
        for nb in self.model.neighbors4(self.pos):
            if self._edge_is_door_closed(self.pos, nb):
                d = self._dist(nb, target)
                if d < best_d:
                    best = nb; best_d = d
        if best is not None:
            return self.open_door_between(self.pos, best)
        return False

    def _sidestep_towards(self, target):
        """
        Intenta un paso 'lateral' (sin A*/BFS) hacia vecinos transitables y libres
        que reduzcan (o mantengan) la distancia Manhattan al target.
        """
        if target is None or self.ap <= 0:
            return False
        candidates = []
        best_d = 10**9
        for nb in self.model.neighbors4(self.pos):
            if nb in self.model.fire_positions:
                continue
            if not self.model.can_traverse(self.pos, nb):
                continue
            if not self._cell_free(nb):
                continue
            d = self._dist(nb, target)
            if d <= self._dist(self.pos, target):
                candidates.append((d, nb))
                best_d = min(best_d, d)
        # Priorizamos los que más acercan
        candidates = [nb for (d, nb) in sorted(candidates, key=lambda x: x[0])]
        for nb in candidates:
            if self._try_move(nb):
                self.log.append(f"Paso lateral hacia {target}: {nb}. AP={self.ap}")
                return True
        return False

    def _random_push_door(self):
        """
        En modo random (o fallback), intenta abrir cualquier puerta cerrada adyacente (1 AP).
        """
        if self.ap <= 0:
            return False
        neigh = list(self.model.neighbors4(self.pos))
        rng = getattr(self.model, "random", None)
        if rng: rng.shuffle(neigh)
        else: random.shuffle(neigh)
        for nb in neigh:
            if self._edge_is_door_closed(self.pos, nb):
                if self.open_door_between(self.pos, nb):
                    self.log.append(f"Random: abre puerta hacia {nb}. AP={self.ap}")
                    return True
        return False

