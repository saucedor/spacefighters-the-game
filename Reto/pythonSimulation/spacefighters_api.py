def parse_map_6x8_file(path):
    """
    Formato:
      - 6 líneas con 8 grupos de 4 dígitos 'ULDR': 1=pared, 0=libre.
      - POIs: r c t  (t in {v|f})  -> victima|falsa
      - Fuego: r c   (múltiples líneas) hasta que aparezcan puertas
      - Puertas: r1 c1 r2 c2  (múltiples)
      - Entradas: r c  (múltiples al final)

    Devuelve: dict con W=8, H=6, walls=set(edges), doors=set(edges),
              pois=[((x,y), 'alive'|'none')], fires=set((x,y)), entries=[(x,y)]
    """
    with open(path, "r") as f:
        raw = [ln.strip() for ln in f if ln.strip()]

    H, W = 6, 8
    wall_lines = raw[:H]
    i = H

    def edge(a, b):
        return frozenset((a, b))

    # ---- PAREDES (internas) ----
    walls = set()
    for r in range(H):  # r: 0..5
        groups = wall_lines[r].split()
        if len(groups) != W:
            raise ValueError(f"Línea {r+1}: se esperaban {W} grupos, obtuve {len(groups)}.")
        for c in range(W):  # c: 0..7
            bits = groups[c]
            if len(bits) != 4 or any(ch not in "01" for ch in bits):
                raise ValueError(f"Grupo inválido en r={r+1}, c={c+1}: '{bits}'")
            U, L, D, R = (bits[0] == '1', bits[1] == '1', bits[2] == '1', bits[3] == '1')
            x, y = c, r
            # Sólo añadimos arista si el vecino está dentro del mapa
            if U and y-1 >= 0: walls.add(edge((x, y), (x, y-1)))
            if L and x-1 >= 0: walls.add(edge((x, y), (x-1, y)))
            if D and y+1 < H:  walls.add(edge((x, y), (x, y+1)))
            if R and x+1 < W:  walls.add(edge((x, y), (x+1, y)))

    # ---- POIs (r c t) t in {v,f} ----
    pois = []
    while i < len(raw):
        parts = raw[i].split()
        if len(parts) == 3 and parts[2].lower() in ("v", "f"):
            r, c, t = parts
            r, c = int(r), int(c)
            status = 'alive' if t.lower() == 'v' else 'none'
            pois.append(((c-1, r-1), status))
            i += 1
        else:
            break

    # ---- FUEGO (r c) hasta que aparezcan puertas (4 ints) ----
    fires = set()
    while i < len(raw):
        parts = raw[i].split()
        # si son 4 enteros -> puertas
        if len(parts) == 4 and all(p.replace('-', '').isdigit() for p in parts):
            break
        # si son 2 enteros -> fuego
        if len(parts) == 2 and all(p.replace('-', '').isdigit() for p in parts):
            r, c = map(int, parts)
            fires.add((c-1, r-1))
            i += 1
        else:
            # línea inesperada
            break

    # ---- PUERTAS (r1 c1 r2 c2) hasta que aparezcan entradas (2 ints) ----
    doors = set()
    while i < len(raw):
        parts = raw[i].split()
        if len(parts) == 4 and all(p.replace('-', '').isdigit() for p in parts):
            r1, c1, r2, c2 = map(int, parts)
            a = (c1-1, r1-1); b = (c2-1, r2-1)
            if abs(a[0]-b[0]) + abs(a[1]-b[1]) != 1:
                raise ValueError(f"Puerta no adyacente: {(r1,c1)}~{(r2,c2)}")
            doors.add(edge(a, b))
            i += 1
        else:
            break

    # ---- ENTRADAS (r c) resto del archivo ----
    entries = []
    while i < len(raw):
        parts = raw[i].split()
        if len(parts) == 2 and all(p.replace('-', '').isdigit() for p in parts):
            r, c = map(int, parts)
            entries.append((c-1, r-1))
            i += 1
        else:
            raise ValueError(f"Línea no reconocida al final: '{raw[i]}'")

    return dict(W=W, H=H, walls=walls, doors=doors, pois=pois, fires=fires, entries=entries)

