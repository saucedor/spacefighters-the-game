    # ---------- ARISTAS ----------
    def _edge(self, a, b):
        return frozenset((a, b))

    def neighbors4(self, pos):
        x, y = pos
        for nx, ny in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)):
            if 0 <= nx < self.W and 0 <= ny < self.H:
                yield (nx, ny)

    def edge_is_wall_solid(self, a, b):
        e = self._edge(a, b)
        dmg = self.wall_damage_edge.get(e, None)
        # Solo es pared si EXISTE esa arista en wall_damage_edge y su daño < 2
        return (dmg is not None) and (dmg < 2)

    def planning_passable(self, a, b):
        # En planificación, paredes sólidas bloquean; puertas cerradas se permiten
        return not self.edge_is_wall_solid(a, b)

    def can_traverse(self, a, b):
        # Para moverse/actuar: paredes sólidas y puertas cerradas bloquean
        if self.edge_is_wall_solid(a, b):
            return False
        if self.edge_is_door_closed(a, b):
            return False
        return True

    def edge_is_door_closed(self, a, b):
        e = self._edge(a, b)
        return self.door_state_edge.get(e) == "closed"

